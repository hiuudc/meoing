function sampleAnswerBank(labels: string[], defaultMode: AnswerBank["defaultMode"]): AnswerBank {
  return {
    tokens: labels.map((label, index) => ({ id: `sample-token-${index}`, label })),
    separator: "space",
    defaultMode,
  };
}

